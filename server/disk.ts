/**
 * What Claude Code is keeping on disk, by category.
 *
 * Every other pillar reads these files for what they say. This one asks only how
 * much room they take, which turns out to matter: the install here is 1.4 GB and
 * growing, most of it a transcript tree nothing prunes, and the retention window
 * that bounds it is a setting most operators have never looked at.
 *
 * Pure `stat` calls. Nothing is opened, parsed, or interpreted, so this is the
 * one reader whose figures are measured rather than derived - a byte count is
 * not an estimate. The one place judgement enters is which directory belongs to
 * which category, and that mapping is declared below rather than inferred.
 */

export type DiskCategory = {
  key: string;
  label: string;
  /** What lives here, in the operator's terms, and whether losing it costs anything. */
  meaning: string;
  bytes: number;
  files: number;
  /** Newest write anywhere beneath it, so a stale category is visible as stale. */
  newestMtime: string | null;
  path: string;
  present: boolean;
};

export type DiskReport = {
  categories: DiskCategory[];
  totalBytes: number;
  totalFiles: number;
  /** Bytes under the root that no declared category claimed. */
  otherBytes: number;
  /**
   * Directories the walk could not finish. Surfaced because a total that quietly
   * skipped an unreadable subtree understates itself.
   */
  unreadableDirs: number;
  root: string;
  /**
   * The retention setting that bounds the transcript tree, when it is set. The
   * single most useful number next to a large transcript figure, because it says
   * whether the tree is bounded at all.
   */
  cleanupPeriodDays: number | null;
};

