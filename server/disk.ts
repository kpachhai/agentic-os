type Walked = { bytes: number; files: number; newestMtimeMs: number; unreadableDirs: number };

/**
 * Recursive size. Symlinks are counted as the link and never followed: a skill
 * linked out of another checkout would otherwise be billed to this tree, and a
 * link pointing upward would make the walk unbounded.
 */
function walk(dirPath: string): Walked {
  const out: Walked = { bytes: 0, files: 0, newestMtimeMs: 0, unreadableDirs: 0 };
  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dirPath, { withFileTypes: true });
  } catch {
    out.unreadableDirs += 1;
    return out;
  }

  for (const entry of entries) {
    const full = path.join(dirPath, entry.name);
    if (entry.isSymbolicLink()) continue;
    if (entry.isDirectory()) {
      const nested = walk(full);
      out.bytes += nested.bytes;
      out.files += nested.files;
      out.unreadableDirs += nested.unreadableDirs;
      if (nested.newestMtimeMs > out.newestMtimeMs) out.newestMtimeMs = nested.newestMtimeMs;
      continue;
    }
    try {
      const stat = fs.statSync(full);
      out.bytes += stat.size;
      out.files += 1;
      if (stat.mtimeMs > out.newestMtimeMs) out.newestMtimeMs = stat.mtimeMs;
    } catch {
      // Vanished between the listing and the stat. Counting nothing is right.
    }
  }
  return out;
}

function toIso(mtimeMs: number): string | null {
  return mtimeMs > 0 ? new Date(mtimeMs).toISOString() : null;
}

/**
 * How long Claude Code keeps transcripts, when the operator has set it. Read
 * fresh and never cached, and absence is reported as null rather than as the
 * product default, because guessing here would put a made-up bound next to a
 * real size.
 */
function readCleanupPeriodDays(settingsPath: string): number | null {
  try {
    const raw = JSON.parse(fs.readFileSync(settingsPath, "utf8")) as Record<string, unknown>;
    const value = raw.cleanupPeriodDays;
    return typeof value === "number" && Number.isFinite(value) ? value : null;
  } catch {
    return null;
  }
}

export function diskReport(claudeHome: string, settingsPath: string): DiskReport {
  if (!fs.existsSync(claudeHome)) {
    throw new SourceMissingError("claude home", claudeHome);
  }

  const categories: DiskCategory[] = [];
  let totalBytes = 0;
  let totalFiles = 0;
  let unreadableDirs = 0;
  const claimed = new Set<string>();

  for (const category of CATEGORIES) {
    const full = path.join(claudeHome, category.dir);
    claimed.add(category.dir);
    const present = fs.existsSync(full);
    const walked = present
      ? walk(full)
      : { bytes: 0, files: 0, newestMtimeMs: 0, unreadableDirs: 0 };
    unreadableDirs += walked.unreadableDirs;
    totalBytes += walked.bytes;
    totalFiles += walked.files;
    categories.push({
      key: category.key,
      label: category.label,
      meaning: category.meaning,
      bytes: walked.bytes,
      files: walked.files,
      newestMtime: toIso(walked.newestMtimeMs),
      path: full,
      present,
    });
  }

  for (const notable of NOTABLE_FILES) {
    const full = path.join(claudeHome, notable.file);
    claimed.add(notable.file);
    let bytes = 0;
    let mtimeMs = 0;
    let present = false;
    try {
      const stat = fs.statSync(full);
      bytes = stat.size;
      mtimeMs = stat.mtimeMs;
      present = true;
    } catch {
      present = false;
    }
    totalBytes += bytes;
    totalFiles += present ? 1 : 0;
    categories.push({
      key: notable.key,
      label: notable.label,
      meaning: notable.meaning,
      bytes,
      files: present ? 1 : 0,
      newestMtime: toIso(mtimeMs),
      path: full,
      present,
    });
  }

  // Whatever the declared map did not claim. Reported rather than dropped, so
  // the categories cannot silently fail to add up to the install.
  let otherBytes = 0;
  try {
    for (const entry of fs.readdirSync(claudeHome, { withFileTypes: true })) {
      if (claimed.has(entry.name) || entry.isSymbolicLink()) continue;
      const full = path.join(claudeHome, entry.name);
      if (entry.isDirectory()) {
        const walked = walk(full);
        otherBytes += walked.bytes;
        unreadableDirs += walked.unreadableDirs;
      } else {
        try {
          otherBytes += fs.statSync(full).size;
        } catch {
          // Same race as above.
        }
      }
    }
  } catch {
    unreadableDirs += 1;
  }

  categories.sort((left, right) => right.bytes - left.bytes);

  return {
    categories,
    totalBytes: totalBytes + otherBytes,
    totalFiles,
    otherBytes,
    unreadableDirs,
    root: claudeHome,
    cleanupPeriodDays: readCleanupPeriodDays(settingsPath),
  };
}
